"""The ``code`` hop of a need in a docstring autodoc reads.

Autodoc gives a docstring's text the source ``<file>:docstring of <name>``, where
``<name>`` is the object's ``__module__`` and ``__qualname__`` (its definition, not the
path it is documented under). Where the definition that name resolves to holds the
need's text in its docstring, the hop records the file of its module, the language
``python``, and its parts in that file as sphinx-codelinks' Python rule reads them from
the file's syntax: ``class``; ``method`` for a ``def`` directly in a class; ``function``
for any other ``def``; ``<locals>`` implied after a ``def``, not an entry. An attribute
(a ``#:`` comment) is a leaf ``attribute``. A module docstring has no semantic location.
Where no definition holding the text is found -- an alias, an override inheriting its
docstring, an object made at run time -- the hop records the file autodoc gives, and no
semantic location: a wrong part is never recorded.

The project, ``doc_test/doc_need_source_autodoc``, documents one docstring of each case;
the file each row names is under its ``src`` directory, outside the Sphinx source
directory.
"""

from __future__ import annotations

import io
import shutil
import warnings
from collections.abc import Iterator
from pathlib import Path

import pytest
from sphinx.testing.util import SphinxTestApp

from sphinx_needs._need_source import (
    NeedSourceHop,
    _docstring_hop,
    _module_splits,
    _python_definitions,
    _python_semantic,
)
from sphinx_needs.data import SphinxNeedsData
from sphinx_needs_testkit import assert_no_warnings
from tests.test_need_source import _compact

PROJECT = Path(__file__).parent / "doc_test" / "doc_need_source_autodoc"

_SHAPES = "code srcdir:../src/docstring_hops/shapes.py (python)"
_FACTORY = "code srcdir:../src/docstring_hops/factory.py (python)"
_COLLIDE = "code srcdir:../src/docstring_hops/collide/__init__.py (python)"
_REEXPORT = "code srcdir:../src/docstring_hops/reexport/main.py (python)"

#: every need's code hop, its first; the second is its page
EXPECTED: dict[str, str] = {
    # the module docstring: the file
    "R_MODULE": _SHAPES,
    "R_FUNC": f"{_SHAPES} :: function 'area_of'",
    "R_CLASS": f"{_SHAPES} :: class 'Shape'",
    "R_METHOD": f"{_SHAPES} :: class 'Shape' > method 'area'",
    # the syntax' kinds, not autodoc's objtypes (which the page hop keeps)
    "R_STATIC": f"{_SHAPES} :: class 'Shape' > method 'make'",
    "R_CLASSMETHOD": f"{_SHAPES} :: class 'Shape' > method 'build'",
    "R_PROPERTY": f"{_SHAPES} :: class 'Shape' > method 'size'",
    "R_NESTED": f"{_SHAPES} :: class 'Shape' > class 'Inner'",
    "R_NESTED_METHOD": f"{_SHAPES} :: class 'Shape' > class 'Inner' > method 'deep'",
    "R_EXCEPTION": f"{_SHAPES} :: class 'Oops'",
    # documented under ``Shape`` in shapes.py, defined in base.py: the file it is in
    "R_INHERITED": (
        "code srcdir:../src/docstring_hops/base.py (python)"
        " :: class 'Base' > method 'describe'"
    ),
    # ``make.<locals>.Made``: the ``<locals>`` is implied by the function before it
    "R_MADE": f"{_FACTORY} :: function 'make' > class 'Made'",
    "R_MADE_METHOD": f"{_FACTORY} :: function 'make' > class 'Made' > method 'go'",
    # attributes (``#:``): a leaf ``attribute``, under its class or at the file
    "R_ATTR": f"{_SHAPES} :: class 'Shape' > attribute 'sides'",
    "R_DATA": f"{_SHAPES} :: attribute 'LIMIT'",
    # a class named like a submodule its package imported first: the class, not the
    # submodule (whose docstring does not hold the text) nor its ``area``
    "R_COLLIDE": f"{_COLLIDE} :: class 'Thing'",
    "R_COLLIDE_METHOD": f"{_COLLIDE} :: class 'Thing' > method 'area'",
    # a module whose package binds its name to a function it re-exports, and one its
    # package no longer binds: the module still
    "R_MAIN": f"{_REEXPORT} :: function 'main'",
    "R_MAIN_HELPER": f"{_REEXPORT} :: function 'helper'",
    "R_DELETED": (
        "code srcdir:../src/docstring_hops/deleted/_impl.py (python) :: function 'g'"
    ),
    # a need whose title another need, in the function's docstring, has too: every line
    # of the need is checked, so the alias' need is not taken for the function's
    "R_SAME_A": f"{_FACTORY} :: function 'titled'",
    "R_SAME_B": _FACTORY,
    # a function nested past what a recursive walk takes (generated by ``hops``)
    "R_DEEP": (
        "code srcdir:../src/docstring_hops/deep.py (python) :: function 'documented'"
    ),
    # autodoc names each of these by an object whose docstring does not hold the text:
    # the file autodoc gives, nothing finer
    # - an alias of a function of the same file, of another file, of a method in its
    #   class: autodoc names the alias' comment by the function
    "R_ALIAS_HERE": _FACTORY,
    "R_ALIAS_THERE": _FACTORY,
    "R_CLASS_ALIAS": _SHAPES,
    # - an override without a docstring, which inherits the base method's
    "R_OVERRIDE": _SHAPES,
    # - an alias of a function with no Python source (``builtins.len``)
    "R_ALIAS_BUILTIN": _FACTORY,
    # - a function made by ``exec``: its name is no definition of the file's syntax
    "R_GENERATED": _FACTORY,
    # - a function whose ``__module__`` names the package re-exporting it: the
    #   package's file, which does not hold the text either (a KNOWN GAP, as it was)
    "R_REWRITE": "code srcdir:../src/docstring_hops/rewrite/__init__.py (python)",
}

#: a module with a documented function, and an ``elif`` chain 1200 deep: valid Python,
#: deeper than the recursion limit
DEEP = '''def documented():
    """A function beside a deep one.

    .. req:: Beside a deep function
       :id: R_DEEP
    """


def dispatch(x):
    if x == 0:
        return 0
''' + "".join(f"    elif x == {i}:\n        return {i}\n" for i in range(1, 1200))


@pytest.fixture(scope="module")
def hops(
    tmp_path_factory: pytest.TempPathFactory,
) -> Iterator[dict[str, tuple[NeedSourceHop, ...]]]:
    """The project, built once from its own copy, with the deep module written into
    it: every need's hops."""
    root = tmp_path_factory.mktemp("autodoc") / "project"
    shutil.copytree(PROJECT, root)
    (root / "src" / "docstring_hops" / "deep.py").write_text(DEEP, encoding="utf-8")
    with (root / "docs" / "index.rst").open("a", encoding="utf-8") as index:
        index.write("\n.. automodule:: docstring_hops.deep\n   :members: documented\n")
    app = SphinxTestApp(
        "html",
        srcdir=root / "docs",
        freshenv=True,
        status=io.StringIO(),
        warning=io.StringIO(),
    )
    try:
        app.build()
        assert_no_warnings(app)
        yield {
            need_id: need.source.hops
            for need_id, need in SphinxNeedsData(app.env).get_needs_view().items()
        }
    finally:
        app.cleanup()


def test_the_project_holds_exactly_the_pinned_needs(
    hops: dict[str, tuple[NeedSourceHop, ...]],
) -> None:
    assert sorted(hops) == sorted(EXPECTED)


@pytest.mark.parametrize("need_id", sorted(EXPECTED))
def test_a_docstring_s_code_hop(
    hops: dict[str, tuple[NeedSourceHop, ...]], need_id: str
) -> None:
    code, page = hops[need_id]
    assert _compact(code) == EXPECTED[need_id]
    assert (page.kind, page.document) == ("page", "index")


# --- the rule, on text --------------------------------------------------------------

_TEXT = """\
import typing


def outer():
    def inner():
        class Local:
            def m(self): ...


async def fetch(): ...


class Twice: ...


def Twice(): ...


value = 1


def value(): ...


first, (second, *rest) = 1, (2, 3)
annotated: int

if typing.TYPE_CHECKING:
    def guarded(): ...


class K:
    try:
        slot: int = 0
    except Exception:
        pass

    def method(self):
        local = 1
        self.instance = 2
"""


@pytest.mark.parametrize(
    ("qualname", "expected"),
    [
        ("outer", [("function", "outer")]),
        ("outer.<locals>.inner", [("function", "outer"), ("function", "inner")]),
        (
            "outer.<locals>.inner.<locals>.Local.m",
            [
                ("function", "outer"),
                ("function", "inner"),
                ("class", "Local"),
                ("method", "m"),
            ],
        ),
        # ``<locals>`` is where Python writes it, and nowhere else
        ("outer.inner", None),
        ("fetch", [("function", "fetch")]),
        # two definitions of one name with different kinds: no guess
        ("Twice", None),
        # a definition wins over an assignment
        ("value", [("function", "value")]),
        ("first", [("attribute", "first")]),
        ("second", [("attribute", "second")]),
        ("rest", [("attribute", "rest")]),
        ("annotated", [("attribute", "annotated")]),
        ("guarded", [("function", "guarded")]),
        ("K.slot", [("class", "K"), ("attribute", "slot")]),
        # a name assigned in a function is no attribute; ``self.x`` is not read
        ("K.method.<locals>.local", None),
        ("K.instance", None),
        ("missing", None),
        # the module itself
        ("", None),
    ],
)
def test_the_rule_reads_the_syntax(
    qualname: str, expected: list[tuple[str, str]] | None
) -> None:
    semantic = _python_semantic(qualname, _TEXT)
    assert (
        None if semantic is None else [(part.kind, part.name) for part in semantic]
    ) == expected


def test_text_that_does_not_parse_names_nothing() -> None:
    assert _python_semantic("f", "def f(:\n") is None


def test_the_name_splits_at_each_module_longest_first() -> None:
    assert list(_module_splits("sphinx_needs._need_source.NeedSourceHop.kind")) == [
        ("sphinx_needs._need_source", "NeedSourceHop.kind"),
        ("sphinx_needs", "_need_source.NeedSourceHop.kind"),
    ]
    assert list(_module_splits("sphinx_needs")) == [("sphinx_needs", "")]
    assert list(_module_splits("no_such_module_anywhere.f")) == []


def test_a_walk_past_the_recursion_limit_reads_the_syntax() -> None:
    """The walk is iterative over statements: a valid module of any depth the parser
    takes is read, never a ``RecursionError``."""
    assert _python_semantic("dispatch", DEEP) is not None
    chain = "x = " + "+".join(["1"] * 3000) + "\n\n\ndef f(): ...\n"
    assert [(p.kind, p.name) for p in _python_semantic("f", chain) or ()] == [
        ("function", "f")
    ]


def test_a_syntax_warning_neither_repeats_nor_fails_the_read() -> None:
    """The import has reported it; under ``-W error`` the read still succeeds."""
    _python_definitions.cache_clear()
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        assert _python_semantic("f", 'def f():\n    return "\\d"\n') is not None


def test_a_definition_whose_docstring_does_not_hold_the_text_is_not_trusted(
    tmp_path: Path,
) -> None:
    """``__main__`` (here, pytest's) defines no ``Missing``, and this module's
    ``test_the_rule_reads_the_syntax`` has no docstring holding the text: the file
    autodoc gives, nothing finer. With no text, nothing is trusted."""
    given = tmp_path / "given.py"
    for name, text in (
        ("__main__.Missing", ".. req:: X"),
        (f"{__name__}.test_the_rule_reads_the_syntax", ".. req:: X"),
        (f"{__name__}.test_the_rule_reads_the_syntax", None),
    ):
        hop = _docstring_hop(tmp_path, f"{given}:docstring of {name}", text)
        assert hop.semantic is None
        assert hop.physical is not None
        assert hop.physical.path == "given.py"
    # and where it does: this test's own docstring holds its first line
    hop = _docstring_hop(
        tmp_path,
        f"{given}:docstring of {__name__}."
        "test_a_definition_whose_docstring_does_not_hold_the_text_is_not_trusted",
        "autodoc gives, nothing finer. With no text, nothing is trusted.",
    )
    assert [(p.kind, p.name) for p in hop.semantic or ()] == [
        (
            "function",
            "test_a_definition_whose_docstring_does_not_hold_the_text_is_not_trusted",
        )
    ]
    assert hop.physical is not None
    assert hop.physical.path is not None
    assert hop.physical.path.endswith("test_need_source_autodoc.py")
